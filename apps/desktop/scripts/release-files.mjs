// Release files for in-app updates and Homebrew (ADR-0049, doc 19).
//
//   node scripts/release-files.mjs --dir dist --version 0.2.0 --repo owner/thoth [--notes "…"]
//
// Reads the installers and their `.sig` files that the Desktop workflow collected under stable
// names, and writes:
// - <dir>/latest.json: the Tauri updater manifest, when the build was signed;
// - Casks/thoth.rb at the repo root: the Homebrew cask, with each DMG's SHA-256.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

/** Updater platform → the stable file name the workflow gives that platform's update bundle. */
export const UPDATE_FILES = {
  "darwin-aarch64": "Thoth-macOS-arm64.app.tar.gz",
  "darwin-x86_64": "Thoth-macOS-x64.app.tar.gz",
  "windows-x86_64": "Thoth-Windows-x64-setup.exe",
  "linux-x86_64": "Thoth-Linux-x86_64.AppImage",
};

/** The DMGs the cask installs, by Homebrew arch. */
export const DMG_FILES = { arm: "Thoth-macOS-arm64.dmg", intel: "Thoth-macOS-x64.dmg" };

const download = (repo, version, name) =>
  `https://github.com/${repo}/releases/download/v${version}/${name}`;

/**
 * The updater manifest. `sigs` maps a file name to its signature (the `.sig` file's text).
 * Platforms without a signature are left out; null when none are signed.
 */
export function updaterManifest({ version, repo, notes, pubDate, sigs }) {
  const platforms = {};
  for (const [platform, name] of Object.entries(UPDATE_FILES)) {
    const signature = sigs[name]?.trim();
    if (signature) platforms[platform] = { signature, url: download(repo, version, name) };
  }
  if (Object.keys(platforms).length === 0) return null;
  return { version, notes: notes ?? "", pub_date: pubDate, platforms };
}

/**
 * The Homebrew cask. `sha` maps a DMG name to its SHA-256. Without both checksums (no release
 * yet) the cask skips the check.
 */
export function homebrewCask({ version, repo, sha }) {
  const arm = sha[DMG_FILES.arm];
  const intel = sha[DMG_FILES.intel];
  const sums =
    arm && intel ? `sha256 arm:   "${arm}",\n         intel: "${intel}"` : "sha256 :no_check";
  return `# Generated by apps/desktop/scripts/release-files.mjs on each release (ADR-0049).
# The tap is this repository:
#   brew tap ${repo.split("/")[0]}/thoth https://github.com/${repo}
#   brew install --cask thoth
cask "thoth" do
  arch arm: "arm64", intel: "x64"

  version "${version}"
  ${sums}

  url "https://github.com/${repo}/releases/download/v#{version}/Thoth-macOS-#{arch}.dmg"
  name "Thoth"
  desc "Local-first study app: PDFs, videos and web pages into notes, quizzes and flashcards"
  homepage "https://github.com/${repo}"

  livecheck do
    url :url
    strategy :github_latest
  end

  # Thoth updates itself from GitHub Releases; \`brew upgrade --greedy\` also works.
  auto_updates true
  depends_on macos: ">= :big_sur"

  app "Thoth.app"

  # The app is not notarised yet, so macOS would refuse to open it from a quarantined download.
  postflight do
    system_command "/usr/bin/xattr",
                   args: ["-dr", "com.apple.quarantine", "#{appdir}/Thoth.app"],
                   sudo: false
  end

  zap trash: [
    "~/Library/Application Support/app.thoth.desktop",
    "~/Library/Caches/app.thoth.desktop",
    "~/Library/Logs/app.thoth.desktop",
    "~/Library/WebKit/app.thoth.desktop",
  ]
end
`;
}

function main() {
  const { values } = parseArgs({
    options: {
      dir: { type: "string" },
      version: { type: "string" },
      repo: { type: "string" },
      notes: { type: "string" },
    },
  });
  const { dir, repo } = values;
  const version = values.version?.replace(/^v/, "");
  if (!dir || !version || !repo) {
    console.error("Usage: release-files.mjs --dir <dist> --version <x.y.z> --repo <owner/name>");
    process.exit(2);
  }
  const sigs = {};
  for (const name of Object.values(UPDATE_FILES)) {
    const p = join(dir, `${name}.sig`);
    if (existsSync(p)) sigs[name] = readFileSync(p, "utf8");
  }
  const manifest = updaterManifest({
    version,
    repo,
    notes: values.notes,
    pubDate: new Date().toISOString(),
    sigs,
  });
  if (manifest) {
    writeFileSync(join(dir, "latest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
    console.log(`latest.json: ${Object.keys(manifest.platforms).join(", ")}`);
  } else {
    console.log("No .sig files: this release is not signed, so no latest.json (ADR-0049).");
  }

  const sha = {};
  for (const name of Object.values(DMG_FILES)) {
    const p = join(dir, name);
    if (existsSync(p)) sha[name] = createHash("sha256").update(readFileSync(p)).digest("hex");
  }
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
  writeFileSync(join(root, "Casks/thoth.rb"), homebrewCask({ version, repo, sha }));
  console.log(`Casks/thoth.rb: ${version} (${Object.keys(sha).length} DMG checksums)`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
